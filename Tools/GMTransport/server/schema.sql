CREATE TABLE IF NOT EXISTS gm_transport_route (
 entry INT UNSIGNED NOT NULL PRIMARY KEY,
 source INT UNSIGNED NOT NULL,
 map INT UNSIGNED NOT NULL,
 speed DOUBLE NOT NULL,
 enabled TINYINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gm_transport_revision (
 entry INT UNSIGNED NOT NULL PRIMARY KEY,
 revision INT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gm_transport_history (
 entry INT UNSIGNED NOT NULL,
 revision INT UNSIGNED NOT NULL,
 saved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 payload LONGTEXT NOT NULL,
 PRIMARY KEY(entry,revision)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gm_transport_native (
 entry INT UNSIGNED NOT NULL PRIMARY KEY,
 speed INT UNSIGNED NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gm_transport_native_node (
 entry INT UNSIGNED NOT NULL,
 node INT UNSIGNED NOT NULL,
 x DOUBLE NOT NULL, y DOUBLE NOT NULL, z DOUBLE NOT NULL,
 wait_seconds INT UNSIGNED NOT NULL,
 PRIMARY KEY(entry,node)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gm_transport_route_node (
 entry INT UNSIGNED NOT NULL,
 node INT UNSIGNED NOT NULL,
 x DOUBLE NOT NULL, y DOUBLE NOT NULL, z DOUBLE NOT NULL,
 wait_seconds DOUBLE NOT NULL DEFAULT 0,
 PRIMARY KEY(entry,node),
 CONSTRAINT gm_transport_route_node_parent FOREIGN KEY(entry) REFERENCES gm_transport_route(entry)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS gm_transport_route_node_map (
 entry INT UNSIGNED NOT NULL,
 node INT UNSIGNED NOT NULL,
 map INT UNSIGNED NOT NULL,
 PRIMARY KEY(entry,node),
 CONSTRAINT gm_transport_node_map_parent FOREIGN KEY(entry,node)
 REFERENCES gm_transport_route_node(entry,node) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS gm_transport_node_meta (
 entry INT UNSIGNED NOT NULL, node INT UNSIGNED NOT NULL, uid INT UNSIGNED NOT NULL,
 map INT UNSIGNED NOT NULL, flags INT UNSIGNED NOT NULL DEFAULT 0,
 arrival INT UNSIGNED NOT NULL DEFAULT 0, departure INT UNSIGNED NOT NULL DEFAULT 0,
 PRIMARY KEY(entry,node), UNIQUE KEY stable_point(entry,uid)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gm_transport_announcement (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 entry INT UNSIGNED NOT NULL, node_uid INT UNSIGNED NOT NULL,
 phase TINYINT UNSIGNED NOT NULL DEFAULT 0, delay_ms INT UNSIGNED NOT NULL DEFAULT 0,
 spawn_id BIGINT UNSIGNED NOT NULL, map INT UNSIGNED NOT NULL,
 mode TINYINT UNSIGNED NOT NULL DEFAULT 1, text TEXT NOT NULL,
 legacy_script INT UNSIGNED NOT NULL DEFAULT 0, legacy_type INT UNSIGNED NOT NULL DEFAULT 0, legacy_id INT UNSIGNED NOT NULL DEFAULT 0,
 enabled TINYINT UNSIGNED NOT NULL DEFAULT 1,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 KEY route(entry)
) ENGINE=InnoDB;
